STANDARD_RATIOS = [
    (1, 1),   # Square
    (4, 3),   # Traditional
    (3, 2),   # Photography
    (16, 9),  # Widescreen
    (16, 10), # Monitors
    (21, 9),  # Ultrawide
    (9, 16),  # Vertical
    (3, 1),   # Panoramic
    (1, 3),   # Vertical extreme
    (5, 4),   # Old format
    (3, 4),   # Vertical traditional
    (2, 3),   # Vertical photography
]


@lru_cache(maxsize=128)
def _compute_ratio_info(w: int, h: int) -> Optional[Tuple[str, str]]:
    if w == 0 or h == 0:
        return None

    is_vertical = h > w
    if is_vertical:
        w, h = h, w

    current_ratio = w / h

    best_match = None
    best_diff = float('inf')

    for std_w, std_h in STANDARD_RATIOS:
        if std_h > std_w:
            cmp_w, cmp_h = std_h, std_w
        else:
            cmp_w, cmp_h = std_w, std_h

        standard_ratio = cmp_w / cmp_h
        diff = abs(current_ratio - standard_ratio) / standard_ratio

        if diff < best_diff:
            best_diff = diff
            tight_margin = 3 / max(w, h)
            wide_margin = 0.15

            if diff <= tight_margin:
                sign = ''
            elif diff <= wide_margin:
                sign = '+' if current_ratio > standard_ratio else '-'
            else:
                continue

            if is_vertical:
                best_match = (f"{std_h}:{std_w}", sign)
            else:
                best_match = (f"{std_w}:{std_h}", sign)

    return best_match

class HotkeyRecorder(QWidget):
    key_signal = pyqtSignal(str)
    active_recorder = None

    def __init__(self, initial_value, parent=None):
        super().__init__(parent)
        self.is_recording = False
        self.hook_id = None
        self.recorded_keys = []
        
        layout = QHBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        self.line_edit = QLineEdit(initial_value)
        self.line_edit.setReadOnly(True)
        self.btn = QPushButton(tr("settings.btn.record"))
        self.btn.setFixedWidth(80)
        self.btn.setFocusPolicy(Qt.FocusPolicy.NoFocus) 
        self.btn.clicked.connect(self.toggle_recording)
        layout.addWidget(self.line_edit)
        layout.addWidget(self.btn)
        
        self.key_signal.connect(self._add_key)

    def toggle_recording(self):
        if not self.is_recording:
            self.start_recording()
        else:
            self.stop_recording()

    def start_recording(self):
        # If another recorder is active, stop it. It may be a Qt widget
        # that was already destroyed (dialog closed in a previous session);
        # in that case just clear the reference to avoid RuntimeError.
        prev = HotkeyRecorder.active_recorder
        if prev is not None and prev is not self:
            try:
                prev.stop_recording()
            except RuntimeError:
                HotkeyRecorder.active_recorder = None

        HotkeyRecorder.active_recorder = self
        self.is_recording = True
        self.btn.setText(tr("settings.btn.recording"))
        self.btn.setStyleSheet(f"background-color: {ThemeManager.instance().palette.recording_btn_bg}; color: {ThemeManager.instance().palette.recording_btn_text}; font-weight: bold;")
        self.line_edit.setText("")
        self.line_edit.setPlaceholderText(tr("settings.placeholder.record"))
        self.recorded_keys = []

        # Desactivar atajos globales para evitar que se disparen mientras grabamos
        keyboard.unhook_all()

        # Start the hook to capture keystrokes
        self.hook_id = keyboard.hook(self._on_key_event)

    def stop_recording(self):
        if not self.is_recording:
            return

        self.is_recording = False
        self.btn.setText(tr("settings.btn.record"))
        self.btn.setStyleSheet("")
        if self.hook_id:
            try:
                keyboard.unhook(self.hook_id)
            except (KeyError, ValueError):
                pass
            self.hook_id = None

        if HotkeyRecorder.active_recorder is self:
            HotkeyRecorder.active_recorder = None

    def _on_key_event(self, event):
        if event.event_type == keyboard.KEY_DOWN:
            # Emit signal to update UI from the main thread
            self.key_signal.emit(event.name)

    def _add_key(self, key_name):
        # Avoid capturing key events that activate the button when
        # using keyboard to press "Listo"
        if key_name in ("space", "enter") and not self.recorded_keys:
            return
            
        if key_name not in self.recorded_keys:
            self.recorded_keys.append(key_name)
            self.line_edit.setText("+".join(self.recorded_keys))

    def text(self):
        return self.line_edit.text()

