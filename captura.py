# Centralised temp-file management to avoid leaks in %TEMP%.
# All temp files generated by "Abrir con..." and the Auto action are created
# inside this directory, which is purged at startup (cleans leftovers from
# previous sessions after an abrupt exit) and at exit.
CAPTURA_TEMP_DIR = os.path.join(tempfile.gettempdir(), 'kdgdkd_captura')


def _cleanup_captura_temp_dir():
    if not os.path.isdir(CAPTURA_TEMP_DIR):
        return
    try:
        for name in os.listdir(CAPTURA_TEMP_DIR):
            try:
                os.remove(os.path.join(CAPTURA_TEMP_DIR, name))
            except OSError:
                # The external viewer may still have the file open; ignore
                # it and retry on the next run.
                pass
    except OSError:
        pass


def new_temp_image_path(suffix=".png"):
    os.makedirs(CAPTURA_TEMP_DIR, exist_ok=True)
    fd, path = tempfile.mkstemp(suffix=suffix, dir=CAPTURA_TEMP_DIR)
    os.close(fd)
    return path


_cleanup_captura_temp_dir()
atexit.register(_cleanup_captura_temp_dir)

