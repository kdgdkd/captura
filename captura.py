    # ------------------------------------------------------------
    # Active window capture (Windows only)
    # ------------------------------------------------------------
    def capture_active_window(self):
        if os.name != 'nt':
            self.start_capture()
            return

        import ctypes
        from ctypes import wintypes

        user32 = ctypes.windll.user32

        pt = wintypes.POINT()
        user32.GetCursorPos(ctypes.byref(pt))
        hwnd = user32.WindowFromPoint(pt.x, pt.y)

        if hwnd:
            owner = user32.GetAncestor(hwnd, 3)  # GA_ROOTOWNER
            if owner:
                hwnd = owner

        if not hwnd or not user32.IsWindowVisible(hwnd):
            self.start_capture()
            return

        rect = wintypes.RECT()
        if not user32.GetWindowRect(hwnd, ctypes.byref(rect)):
            self.start_capture()
            return

        win_w = rect.right - rect.left
        win_h = rect.bottom - rect.top
        if win_w <= 0 or win_h <= 0:
            self.start_capture()
            return

        screen = QApplication.screenAt(QPoint(rect.left, rect.top))
        if not screen:
            screen = self.app.primaryScreen()

        full_screenshot = screen.grabWindow(0)
        ratio = full_screenshot.devicePixelRatio()
        screen_geom = screen.geometry()
        physical_offset_x = screen_geom.x() * ratio
        physical_offset_y = screen_geom.y() * ratio

        logical_x = int((rect.left - physical_offset_x) / ratio)
        logical_y = int((rect.top - physical_offset_y) / ratio)
        logical_w = int(win_w / ratio)
        logical_h = int(win_h / ratio)

        self.overlay = CaptureOverlay(full_screenshot, tray_icon=self.tray_icon)
        self.overlay.selection_rect = QRect(logical_x, logical_y, logical_w, logical_h)
        self.overlay.show()
        self.overlay.show_export_menu(QCursor.pos())

