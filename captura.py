    def eventFilter(self, obj, event):
        _drag_targets = [self.panel, self.btn_copy, self.btn_save,
                         self.btn_open, self.btn_cancel]
        if self.btn_auto is not None:
            _drag_targets.append(self.btn_auto)
        if obj in _drag_targets:
            t = event.type()
            if t == QEvent.Type.MouseButtonPress and event.button() == Qt.MouseButton.LeftButton:
                self._drag_start_pos = event.globalPosition().toPoint()
            elif t == QEvent.Type.MouseMove and self._drag_start_pos is not None:
                delta = event.globalPosition().toPoint() - self._drag_start_pos
                if delta.manhattanLength() >= QApplication.startDragDistance():
                    self._drag_start_pos = None
                    self._start_drag()
                    return True
            elif t == QEvent.Type.MouseButtonRelease:
                self._drag_start_pos = None
        return super().eventFilter(obj, event)

    def _start_drag(self):
        if self.selection_rect.isNull():
            return
        pixmap = self.get_cropped_pixmap()
        temp_path = new_temp_image_path(".png")
        pixmap.save(temp_path, format="PNG")

        drag = QDrag(self)
        mime = QMimeData()
        mime.setImageData(pixmap.toImage())
        mime.setUrls([QUrl.fromLocalFile(temp_path)])
        drag.setMimeData(mime)

        thumb = pixmap.scaled(120, 90, Qt.AspectRatioMode.KeepAspectRatio,
                              Qt.TransformationMode.SmoothTransformation)
        drag.setPixmap(thumb)
        drag.setHotSpot(QPoint(thumb.width() // 2, thumb.height() // 2))
        drag.exec(Qt.DropAction.CopyAction)

    def create_svg_icon(self, svg_string: str, color: str = "#ffffff",
                         size: int = 18) -> QIcon:
        """Convierte un string SVG en un QIcon con un color específico"""
        colored_svg = svg_string.replace('stroke="currentColor"', f'stroke="{color}"')
        
        pixmap = QPixmap(size, size)
        pixmap.fill(Qt.GlobalColor.transparent)
        renderer = QSvgRenderer(bytes(colored_svg, 'utf-8'))
        painter = QPainter(pixmap)
        renderer.render(painter)
        painter.end()
        return QIcon(pixmap)

