class Translator:
    _instance = None

    def __init__(self):
        self._strings = {}
        self._locale = "es"

    @classmethod
    def instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def t(self, key: str, **kwargs) -> str:
        text = self._strings.get(key, key)
        if kwargs:
            return text.format(**kwargs)
        return text

    def load_locale(self, locale: str):
        base_dir = os.path.dirname(os.path.abspath(__file__))
        locale_file = os.path.join(base_dir, 'locales', f'{locale}.json')
        try:
            with open(locale_file, 'r', encoding='utf-8') as f:
                self._strings = json.load(f)
            self._locale = locale
        except (FileNotFoundError, json.JSONDecodeError):
            if locale != 'es':
                self.load_locale('es')

    @property
    def locale(self) -> str:
        return self._locale


def tr(key: str, **kwargs) -> str:
    return Translator.instance().t(key, **kwargs)


def _setup_logging():
    log_dir = os.path.join(os.environ.get('LOCALAPPDATA', tempfile.gettempdir()), 'Captura')
    os.makedirs(log_dir, exist_ok=True)
    log_path = os.path.join(log_dir, 'captura.log')
    handler = RotatingFileHandler(log_path, maxBytes=1_000_000, backupCount=2, encoding='utf-8')
    handler.setFormatter(logging.Formatter('%(asctime)s %(levelname)s %(message)s'))
    logging.basicConfig(level=logging.WARNING, handlers=[handler])

    def _excepthook(exc_type, exc_val, exc_tb):
        logging.critical("Excepción no manejada", exc_info=(exc_type, exc_val, exc_tb))
        sys.__excepthook__(exc_type, exc_val, exc_tb)

    sys.excepthook = _excepthook


_setup_logging()

