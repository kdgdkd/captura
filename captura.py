    def silent_capture(self):
        settings = QSettings(SETTINGS_ORG, SETTINGS_APP)
        action = settings.value("auto_action", "Guardar")
        if action == "---":
            return

        screen = QApplication.screenAt(QCursor.pos())
        if not screen:
            screen = self.app.primaryScreen()
        pixmap = screen.grabWindow(0)

        if action == "Copiar":
            QApplication.clipboard().setPixmap(pixmap)
            self.tray_icon.showMessage(tr("notify.title"), tr("notify.silent_copied"),
                                       QSystemTrayIcon.MessageIcon.Information, 2000)

        elif action == "Guardar":
            save_dir = settings.value("save_dir", os.path.expanduser('~'))
            fmt = settings.value("out_format", "PNG").lower()
            quality = int(settings.value("out_quality", 100))
            os.makedirs(save_dir, exist_ok=True)
            date_str = datetime.now().strftime("%Y%m%d_%H%M%S")
            path = os.path.join(save_dir, f"{date_str}_captura.{fmt}")
            save_fmt = 'JPEG' if fmt == 'jpg' else 'PNG'
            save_quality = quality if save_fmt == 'JPEG' else -1
            if pixmap.save(path, format=save_fmt, quality=save_quality):
                logging.info("Captura silenciosa guardada en %s", path)
                self.tray_icon.showMessage(tr("notify.saved"), path,
                                           QSystemTrayIcon.MessageIcon.Information, 3000)
            else:
                logging.error("Error al guardar captura silenciosa en %s", path)

        elif action == "Abrir":
            temp_path = new_temp_image_path(".png")
            if pixmap.save(temp_path, format="PNG"):
                editor_path = settings.value("editor_path", "")
                parsed = urlparse(editor_path) if editor_path else None
                is_url = parsed and parsed.scheme in ('http', 'https', 'ftp')
                if is_url:
                    QApplication.clipboard().setPixmap(pixmap)
                    webbrowser.open(editor_path)
                elif editor_path and os.path.exists(editor_path):
                    subprocess.Popen([editor_path, temp_path])
                elif os.name == 'nt':
                    subprocess.Popen(['rundll32.exe', 'shell32.dll,OpenAs_RunDLL', temp_path])

